export function zodiacOf(month, day) {
  return ZODIAC.find(({ range: [m1, d1, m2, d2] }) =>
    m1 <= m2
      ? (month === m1 && day >= d1) || (month === m2 && day <= d2)
      : (month === m1 && day >= d1) || (month === m2 && day <= d2)
  ) || null;
}
