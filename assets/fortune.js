// 날짜와 유형을 섞어 만든 값. 같은 날 같은 유형이면 항상 같다.
function seed(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}
const pick = (arr, key) => arr[seed(key) % arr.length];

export function todayKey(d = new Date()) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

export function fortune(type, detail = {}, d = new Date()) {
  const day = todayKey(d);
  const base = day + type;
  const strong = detail.strong || [];
  const care = detail.care || [];
  return {
    day,
    line: pick(LINES, base + "L"),
    keyword: pick(KEYWORDS, base + "K"),
    time: pick(TIMES, base + "T"),
    color: pick(COLORS, base + "C"),
    focus: pick(FOCUS, base + "F"),
    lean: strong.length ? pick(strong, base + "S") : "",
    watch: care.length ? pick(care, base + "W") : ""
  };
}
